import clean from "../../../fixtures/document-compliance/packs/clean/pack.json";
import expiredPassport from "../../../fixtures/document-compliance/packs/expired-passport/pack.json";
import incompleteCertification from "../../../fixtures/document-compliance/packs/incomplete-certification/pack.json";
import nameMismatch from "../../../fixtures/document-compliance/packs/name-mismatch/pack.json";
import stalebill from "../../../fixtures/document-compliance/packs/stale-bill/pack.json";
import tamperedPassport from "../../../fixtures/document-compliance/packs/tampered-passport/pack.json";
import type { RequirementId } from "./domain/rulebook";
import type {
  ClientDeclaration,
  DocumentKind,
  Outcome,
  SourceFormat,
} from "./domain/types";

export type PackDocument = {
  kind: DocumentKind;
  file: string;
  mediaType: string;
  sourceFormat: SourceFormat;
  pages: string[];
};

/** A preset Document pack, generated by `fixtures/document-compliance/generate.py`. */
export type Pack = {
  slug: string;
  title: string;
  flaw: string;
  rulebookId: string;
  prescreenDate: string;
  clientDeclaration: ClientDeclaration;
  documents: PackDocument[];
  expectedFindings: { requirementId: RequirementId; outcome: Outcome }[];
};

export const packs = [
  clean,
  expiredPassport,
  stalebill,
  nameMismatch,
  tamperedPassport,
  incompleteCertification,
] as Pack[];

export function findPack(slug: string): Pack | undefined {
  return packs.find((pack) => pack.slug === slug);
}

/** Where a pack's files live in the `document-compliance` Storage bucket. */
export function storagePath(slug: string, file: string) {
  return `presets/${slug}/${file}`;
}

import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/**
 * Bundles the Screen process (screen-entry.ts and the legacy machine, the
 * Guard and the Books diff it imports) into one CommonJS file for Node in
 * the sandbox. Used by `pnpm build:operator-screen` and by the test that
 * fails when the committed bundle is stale. Not part of the app.
 */
export async function buildScreenBundle(): Promise<string> {
  const result = await build({
    entryPoints: [
      fileURLToPath(new URL("./screen-entry.ts", import.meta.url)),
    ],
    bundle: true,
    write: false,
    platform: "node",
    format: "cjs",
    target: "node22",
    external: ["playwright-core"],
    legalComments: "none",
    charset: "ascii",
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

export const bundleHash = (code: string) =>
  createHash("sha256").update(code).digest("hex").slice(0, 16);

/** The generated module's text for a bundle. */
export function generatedModule(code: string) {
  return [
    "// Generated by `pnpm build:operator-screen` from server/sandbox/screen-entry.ts.",
    "// Do not edit: change the sources and run the script again.",
    `export const SCREEN_BUNDLE_HASH = ${JSON.stringify(bundleHash(code))};`,
    `export const SCREEN_BUNDLE = ${JSON.stringify(code)};`,
    "",
  ].join("\n");
}

import { chromium } from "@playwright/test";
const out = process.argv[2];
const token = process.env.E2E_BYPASS_TOKEN ?? "";
const browser = await chromium.launch({ channel: "chrome" });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 }, extraHTTPHeaders: { "x-e2e-token": token } });
const page = await ctx.newPage();
await page.goto("http://localhost:3112/demos/operator", { waitUntil: "domcontentloaded" });
await page.getByRole("button", { name: /Release a hold/ }).first().click();
await page.getByRole("button", { name: "Take the keyboard" }).click();
const term = page.getByRole("application"); await term.waitFor(); await term.click();
await page.keyboard.type("OPR7"); await page.keyboard.press("Tab"); await page.keyboard.type("MERIDIA1"); await page.keyboard.press("Enter");
await page.keyboard.type("3"); await page.keyboard.press("Enter");
await page.waitForTimeout(500);
await term.scrollIntoViewIfNeeded();
await page.screenshot({ path: `${out}/hand.png` });
await page.goto("http://localhost:3112/demos/operator?tab=connect", { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/connect.png`, fullPage: true });
await page.goto("http://localhost:3112/demos", { waitUntil: "networkidle" });
const card = page.getByRole("link", { name: /Operator/ }).first();
await card.scrollIntoViewIfNeeded(); await card.hover(); await page.waitForTimeout(3500);
await page.screenshot({ path: `${out}/catalog.png` });
await browser.close();
